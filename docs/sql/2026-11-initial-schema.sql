-- Initial schema for an EMPTY application database. Do not use as an upgrade.
-- Run transactionally; the executor must refuse to run if application tables exist.
BEGIN;
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    phone varchar(255),
    cpf varchar(14) UNIQUE,
    zip_code varchar(16),
    street_name varchar(255),
    street_number varchar(32),
    neighborhood varchar(255),
    city varchar(255),
    federal_unit varchar(2),
    role varchar(255) NOT NULL CHECK (role IN ('ADMIN','CLIENT'))
);
CREATE TABLE customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES users(id)
);
CREATE TABLE pets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers(id),
    name varchar(255) NOT NULL,
    species varchar(255),
    breed varchar(255),
    sex varchar(30),
    birth_date date,
    weight numeric(8,2),
    notes varchar(2000)
);
CREATE TABLE services (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    description varchar(255),
    price numeric(10,2) NOT NULL
);
CREATE TABLE charges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    customer_id bigint NOT NULL REFERENCES customers(id),
    pet_id bigint NOT NULL REFERENCES pets(id),
    service_id bigint NOT NULL REFERENCES services(id),
    amount numeric(10,2) NOT NULL,
    service_date date NOT NULL,
    due_date date NOT NULL,
    payment_date timestamp(6),
    status varchar(255) NOT NULL CHECK (status IN ('PENDING','PAYMENT_IN_PROCESS','PAID','OVERDUE','CANCELED')),
    idempotency_key varchar(128),
    issuance_state varchar(24),
    customer_name_snapshot varchar(255),
    pet_name_snapshot varchar(255),
    service_name_snapshot varchar(255),
    c6_bank_slip_id varchar(255),
    c6_external_reference_id varchar(10) UNIQUE,
    barcode varchar(64),
    digitable_line varchar(80),
    mercado_pago_id varchar(255),
    ticket_url varchar(1000)
);
CREATE UNIQUE INDEX ux_charges_idempotency_key ON charges(idempotency_key);
CREATE UNIQUE INDEX ux_charges_bank_slip_id ON charges(c6_bank_slip_id);
CREATE TABLE charge_lines (
    charge_id bigint NOT NULL REFERENCES charges(id),
    line_number integer NOT NULL,
    service_id bigint,
    name varchar(255),
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 100),
    unit_price numeric(10,2),
    PRIMARY KEY (charge_id,line_number)
);
COMMIT;
