BEGIN;
CREATE TABLE IF NOT EXISTS profile_photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    pet_id bigint UNIQUE REFERENCES pets(id) ON DELETE CASCADE,
    jpeg bytea NOT NULL,
    CONSTRAINT ck_profile_photos_owner CHECK ((user_id IS NULL) <> (pet_id IS NULL))
);
COMMIT;
